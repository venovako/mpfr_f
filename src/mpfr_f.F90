  PURE FUNCTION MPFR_GET_SI_F(OP, RND)
    IMPLICIT NONE
    INTERFACE
       PURE FUNCTION MPFR_GET_SI(OP, RND) BIND(C)
         IMPORT
         IMPLICIT NONE
         TYPE(MPFR_T), INTENT(IN) :: OP
         INTEGER(KIND=MPFR_RND_KIND), INTENT(IN), VALUE :: RND
         INTEGER(KIND=c_long) :: MPFR_GET_SI
       END FUNCTION MPFR_GET_SI
    END INTERFACE
    TYPE(MPFR_T), INTENT(IN) :: OP
    INTEGER(KIND=MPFR_RND_KIND), INTENT(IN), OPTIONAL :: RND
    INTEGER(KIND=c_long) :: MPFR_GET_SI_F
    IF (OP%TAG .EQ. TAG_NULL) THEN
       MPFR_GET_SI_F = -HUGE(MPFR_GET_SI_F) - 1_c_long
    ELSE IF (PRESENT(RND)) THEN
       MPFR_GET_SI_F = MPFR_GET_SI(OP, RND)
    ELSE ! default rounding
       MPFR_GET_SI_F = MPFR_GET_SI(OP, MPFR_RND_DEFAULT)
    END IF
  END FUNCTION MPFR_GET_SI_F
  PURE FUNCTION MPFR_GET_FLT_F(OP, RND)
