  PURE SUBROUTINE MPFR_GET_STR_F(S, E, B, N, OP, RND, M)
    IMPLICIT NONE
    INTERFACE
       PURE FUNCTION MPFR_GET_STR(S, E, B, N, OP, RND) BIND(C)
         IMPORT
         IMPLICIT NONE
         TYPE(c_ptr), INTENT(IN), VALUE :: S, E
         INTEGER(KIND=c_int), INTENT(IN), VALUE :: B
         INTEGER(KIND=c_size_t), INTENT(IN), VALUE :: N
         TYPE(MPFR_T), INTENT(IN) :: OP
         INTEGER(KIND=MPFR_RND_KIND), INTENT(IN), VALUE :: RND
         TYPE(c_ptr) :: MPFR_GET_STR
       END FUNCTION MPFR_GET_STR
    END INTERFACE
    CHARACTER(LEN=*), INTENT(OUT), TARGET :: S
    INTEGER(KIND=MPFR_EXP_KIND), INTENT(OUT), TARGET :: E
    INTEGER(KIND=c_int), INTENT(IN) :: B
    INTEGER(KIND=c_size_t), INTENT(IN) :: N
    TYPE(MPFR_T), INTENT(IN) :: OP
    INTEGER(KIND=MPFR_RND_KIND), INTENT(IN), OPTIONAL :: RND
    INTEGER(KIND=c_size_t), INTENT(OUT), OPTIONAL :: M
    TYPE(c_ptr) :: RET
    INTEGER(KIND=c_size_t) :: L
    L = LEN(S)
    IF (L .GE. 1_c_size_t) S(1:1) = '@'
    IF (L .GE. 2_c_size_t) S(2:2) = 'N'
    IF (L .GE. 3_c_size_t) S(3:3) = 'a'
    IF (L .GE. 4_c_size_t) S(4:4) = 'N'
    IF (L .GE. 5_c_size_t) S(5:5) = '@'
    IF (L .GE. 6_c_size_t) S(6:6) = c_null_char
    E = 0_MPFR_EXP_KIND
    IF (N .EQ. 0_c_size_t) THEN
       M = MPFR_GET_STR_NDIGITS(B, OP%MPFR_PREC)
    ELSE
       M = N
    END IF
    IF (L .LT. MAX(M+2_c_size_t, 7_c_size_t)) M = 0_c_size_t
    IF (OP%TAG .EQ. TAG_NULL) THEN
       RET = c_null_ptr
    ELSE IF (PRESENT(RND)) THEN
       IF (M .NE. 0_c_size_t) RET = MPFR_GET_STR(C_LOC(S), C_LOC(E), B, M, OP, RND)
    ELSE ! default rounding
       IF (M .NE. 0_c_size_t) RET = MPFR_GET_STR(C_LOC(S), C_LOC(E), B, M, OP, MPFR_RND_DEFAULT)
    END IF
  END SUBROUTINE MPFR_GET_STR_F

