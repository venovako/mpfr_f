    INTEGER(KIND=MPFR_RND_KIND), INTENT(IN), OPTIONAL :: RND
    INTEGER, INTENT(IN), OPTIONAL :: I
    CHARACTER(KIND=c_char), ALLOCATABLE, TARGET :: C(:)
    TYPE(c_ptr), TARGET :: E
    INTEGER :: L
    IF (ROP%TAG .EQ. TAG_NULL) CALL MPFR_INIT_F(ROP)
    L = LEN_TRIM(S)
    ALLOCATE(C(L+1))
    IF (L .GE. 1) C(1:L) = S(1:L)
    C(L+1) = CHAR(0, c_char)
    E = c_null_ptr
    IF (PRESENT(I)) THEN
       L = I
    ELSE ! default base
       L = 0
    END IF
    IF (PRESENT(RND)) THEN
       ROP%TAG = MPFR_STRTOFR(C_LOC(ROP), C_LOC(C), C_LOC(E), INT(L, c_int), RND)
    ELSE ! default rounding
       ROP%TAG = MPFR_STRTOFR(C_LOC(ROP), C_LOC(C), C_LOC(E), INT(L, c_int), MPFR_RND_DEFAULT)
    END IF
    DEALLOCATE(C)
  END SUBROUTINE MPFR_SET_STR_F

  PURE SUBROUTINE MPFR_RELDIFF_F(ROP, OP1, OP2, RND)
    IMPLICIT NONE
    INTERFACE
       PURE SUBROUTINE MPFR_RELDIFF(ROP, OP1, OP2, RND) BIND(C)
         IMPORT
         IMPLICIT NONE
         TYPE(c_ptr), INTENT(IN), VALUE :: ROP, OP1, OP2
         INTEGER(KIND=MPFR_RND_KIND), INTENT(IN), VALUE :: RND
       END SUBROUTINE MPFR_RELDIFF
    END INTERFACE
    TYPE(MPFR_T), INTENT(INOUT), TARGET :: ROP
    TYPE(MPFR_T), INTENT(IN), TARGET :: OP1, OP2
    INTEGER(KIND=MPFR_RND_KIND), INTENT(IN), OPTIONAL :: RND
    IF (ROP%TAG .EQ. TAG_NULL) THEN
       IF ((OP2%TAG .EQ. TAG_NULL) .OR. (OP1%TAG .EQ. TAG_NULL)) THEN
          CALL MPFR_INIT_F(ROP)
       ELSE
          CALL MPFR_INIT_F(ROP, MAX(OP1%MPFR_PREC, OP2%MPFR_PREC))
       END IF
    END IF
    IF ((OP2%TAG .EQ. TAG_NULL) .OR. (OP1%TAG .EQ. TAG_NULL)) THEN
       CALL MPFR_SET_NAN_F(ROP)
    ELSE IF (PRESENT(RND)) THEN
       CALL MPFR_RELDIFF(C_LOC(ROP), C_LOC(OP1), C_LOC(OP2), RND)
    ELSE ! default rounding
       CALL MPFR_RELDIFF(C_LOC(ROP), C_LOC(OP1), C_LOC(OP2), MPFR_RND_DEFAULT)
    END IF
  END SUBROUTINE MPFR_RELDIFF_F

