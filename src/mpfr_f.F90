  PURE FUNCTION MPFR_IS_INITIALIZED()
    IMPLICIT NONE
    LOGICAL :: MPFR_IS_INITIALIZED
    MPFR_IS_INITIALIZED = (MPFR_PREC_DEFAULT .GT. 0_MPFR_PREC_KIND)
  END FUNCTION MPFR_IS_INITIALIZED

  ! MUST be called before all other subroutines from this module.
  FUNCTION MPFR_INITIALIZE(P, R, EXP_MIN, EXP_MAX)
    IMPLICIT NONE
    INTERFACE
       SUBROUTINE MPFR_SET_DEFAULT_PREC(P) BIND(C)
         IMPORT
         IMPLICIT NONE
         INTEGER(KIND=MPFR_PREC_KIND), INTENT(IN), VALUE :: P
       END SUBROUTINE MPFR_SET_DEFAULT_PREC
    END INTERFACE
    INTERFACE
       SUBROUTINE MPFR_SET_DEFAULT_ROUNDING_MODE(R) BIND(C)
         IMPORT
         IMPLICIT NONE
         INTEGER(KIND=MPFR_RND_KIND), INTENT(IN), VALUE :: R
       END SUBROUTINE MPFR_SET_DEFAULT_ROUNDING_MODE
    END INTERFACE
    INTERFACE
       FUNCTION MPFR_SET_EMIN(E) BIND(C)
         IMPORT
         IMPLICIT NONE
         INTEGER(KIND=MPFR_EXP_KIND), INTENT(IN), VALUE :: E
         INTEGER(KIND=c_int) :: MPFR_SET_EMIN
       END FUNCTION MPFR_SET_EMIN
    END INTERFACE
    INTERFACE
       FUNCTION MPFR_SET_EMAX(E) BIND(C)
         IMPORT
         IMPLICIT NONE
         INTEGER(KIND=MPFR_EXP_KIND), INTENT(IN), VALUE :: E
         INTEGER(KIND=c_int) :: MPFR_SET_EMAX
       END FUNCTION MPFR_SET_EMAX
    END INTERFACE
    INTEGER(KIND=MPFR_PREC_KIND), INTENT(IN), OPTIONAL :: P
    INTEGER(KIND=MPFR_RND_KIND), INTENT(IN), OPTIONAL :: R
    INTEGER(KIND=MPFR_EXP_KIND), INTENT(IN), OPTIONAL :: EXP_MIN, EXP_MAX
    INTEGER :: MPFR_INITIALIZE
    MPFR_INITIALIZE = 0
    IF (PRESENT(EXP_MAX)) THEN
       IF ((EXP_MAX .GE. MPFR_GET_EMAX_MIN()) .AND. (EXP_MAX .LE. MPFR_GET_EMAX_MAX())) THEN
          MPFR_EXP_MAX = EXP_MAX
       ELSE ! error
          MPFR_INITIALIZE = -4
       END IF
    ELSE
       MPFR_EXP_MAX = MPFR_GET_EMAX_MAX()
    END IF
    IF (MPFR_INITIALIZE .NE. 0) RETURN
    IF (PRESENT(EXP_MIN)) THEN
       IF ((EXP_MIN .GE. MPFR_GET_EMIN_MIN()) .AND. (EXP_MIN .LE. MPFR_GET_EMIN_MAX())) THEN
          MPFR_EXP_MIN = EXP_MIN
       ELSE ! error
          MPFR_INITIALIZE = -3
       END IF
    ELSE
       MPFR_EXP_MIN = MPFR_GET_EMIN_MIN()
    END IF
    IF (MPFR_INITIALIZE .NE. 0) RETURN
    IF (PRESENT(R)) THEN
       IF ((R .GE. MPFR_RNDN) .AND. (R .LE. MPFR_RNDF)) THEN
          MPFR_RND_DEFAULT = R
       ELSE ! error
          MPFR_INITIALIZE = -2
       END IF
    ELSE
       MPFR_RND_DEFAULT = MPFR_GET_DEFAULT_ROUNDING_MODE()
    END IF
    IF (MPFR_INITIALIZE .NE. 0) RETURN
    IF (PRESENT(P)) THEN
       IF ((P .GE. MPFR_PREC_MIN) .AND. (P .LE. MPFR_PREC_MAX)) THEN
          MPFR_PREC_DEFAULT = P
       ELSE ! error
          MPFR_INITIALIZE = -1
       END IF
    ELSE
       MPFR_PREC_DEFAULT = MPFR_GET_DEFAULT_PREC()
    END IF
    IF (MPFR_INITIALIZE .NE. 0) RETURN
    MPFR_INITIALIZE = INT(MPFR_SET_EMAX(MPFR_EXP_MAX))
    IF (MPFR_INITIALIZE .NE. 0) RETURN
    MPFR_INITIALIZE = INT(MPFR_SET_EMIN(MPFR_EXP_MIN))
    IF (MPFR_INITIALIZE .NE. 0) RETURN
    CALL MPFR_SET_DEFAULT_ROUNDING_MODE(MPFR_RND_DEFAULT)
    CALL MPFR_SET_DEFAULT_PREC(MPFR_PREC_DEFAULT)
  END FUNCTION MPFR_INITIALIZE
  SUBROUTINE MPFR_FINALIZE()
    IMPLICIT NONE
    INTERFACE
       SUBROUTINE MPFR_FREE_CACHE() BIND(C)
         IMPLICIT NONE
       END SUBROUTINE MPFR_FREE_CACHE
    END INTERFACE
    CALL MPFR_FREE_CACHE()
  END SUBROUTINE MPFR_FINALIZE

  PURE SUBROUTINE MPFR_CLEAR_F(M)
    IMPLICIT NONE
    INTERFACE
       PURE SUBROUTINE MPFR_CLEAR(M) BIND(C)
         IMPORT
         IMPLICIT NONE
         TYPE(MPFR_T), INTENT(INOUT) :: M
       END SUBROUTINE MPFR_CLEAR
    END INTERFACE
    TYPE(MPFR_T), INTENT(INOUT) :: M
    IF (M%TAG .NE. TAG_NULL) THEN
       CALL MPFR_CLEAR(M)
       M%TAG = TAG_NULL
    END IF
  END SUBROUTINE MPFR_CLEAR_F
  PURE SUBROUTINE MPFR_INIT_F(LHS, P)
    IMPLICIT NONE
    INTERFACE
       PURE SUBROUTINE MPFR_INIT2(M, P) BIND(C)
         IMPORT
         IMPLICIT NONE
         TYPE(MPFR_T), INTENT(INOUT) :: M
         INTEGER(KIND=MPFR_PREC_KIND), INTENT(IN), VALUE :: P
       END SUBROUTINE MPFR_INIT2
    END INTERFACE
    TYPE(MPFR_T), INTENT(INOUT) :: LHS
    INTEGER(KIND=MPFR_PREC_KIND), INTENT(IN), OPTIONAL :: P
    IF (LHS%TAG .NE. TAG_NULL) CALL MPFR_CLEAR_F(LHS)
    IF (PRESENT(P)) THEN
       CALL MPFR_INIT2(LHS, P)
    ELSE ! default
       CALL MPFR_INIT2(LHS, MPFR_PREC_DEFAULT)
    END IF
    LHS%TAG = TAG_EXACT
  END SUBROUTINE MPFR_INIT_F
  PURE SUBROUTINE MPFR_SET_F(LHS, RHS, RND)
    IMPLICIT NONE
    INTERFACE
       PURE FUNCTION MPFR_SET(LHS, RHS, RND) BIND(C)
         IMPORT
         IMPLICIT NONE
         TYPE(c_ptr), INTENT(IN), VALUE :: LHS, RHS
         INTEGER(KIND=MPFR_RND_KIND), INTENT(IN), VALUE :: RND
         INTEGER(KIND=c_int) :: MPFR_SET
       END FUNCTION MPFR_SET
    END INTERFACE
    TYPE(MPFR_T), INTENT(INOUT), TARGET :: LHS
    TYPE(MPFR_T), INTENT(IN), TARGET :: RHS
    INTEGER(KIND=MPFR_RND_KIND), INTENT(IN), OPTIONAL :: RND
    IF (RHS%TAG .EQ. TAG_NULL) THEN
       IF (LHS%TAG .NE. TAG_NULL) CALL MPFR_CLEAR_F(LHS)
       RETURN
    ELSE IF (LHS%TAG .EQ. TAG_NULL) THEN
       CALL MPFR_INIT_F(LHS, RHS%MPFR_PREC)
    END IF
    IF (PRESENT(RND)) THEN
       LHS%TAG = MPFR_SET(C_LOC(LHS), C_LOC(RHS), RND)
    ELSE ! default
       LHS%TAG = MPFR_SET(C_LOC(LHS), C_LOC(RHS), MPFR_RND_DEFAULT)
    END IF
  END SUBROUTINE MPFR_SET_F
  PURE SUBROUTINE MPFR_SWAP_F(X, Y)
    IMPLICIT NONE
    INTERFACE
       PURE SUBROUTINE MPFR_SWAP(X, Y) BIND(C)
         IMPORT
         IMPLICIT NONE
         TYPE(MPFR_T), INTENT(INOUT) :: X, Y
       END SUBROUTINE MPFR_SWAP
    END INTERFACE
    TYPE(MPFR_T), INTENT(INOUT) :: X, Y
    INTEGER(KIND=MPFR_TAG_KIND) :: XT, YT
    XT = X%TAG
    YT = Y%TAG
    CALL MPFR_SWAP(X, Y)
    X%TAG = YT
    Y%TAG = XT
  END SUBROUTINE MPFR_SWAP_F

