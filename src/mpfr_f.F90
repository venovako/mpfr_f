  ! MUST be called before all other subroutines from this module.
  FUNCTION MPFR_INITIALIZE(P, R, EXP_MIN, EXP_MAX)
    IMPLICIT NONE
    INTERFACE
       SUBROUTINE MPFR_SET_DEFAULT_PREC(P) BIND(C)
         IMPORT
         IMPLICIT NONE
         INTEGER(KIND=MPFR_PREC_KIND), INTENT(IN), VALUE :: P
       END SUBROUTINE MPFR_SET_DEFAULT_PREC
    END INTERFACE
    INTERFACE
       SUBROUTINE MPFR_SET_DEFAULT_ROUNDING_MODE(R) BIND(C)
         IMPORT
         IMPLICIT NONE
         INTEGER(KIND=MPFR_RND_KIND), INTENT(IN), VALUE :: R
       END SUBROUTINE MPFR_SET_DEFAULT_ROUNDING_MODE
    END INTERFACE
    INTERFACE
       FUNCTION MPFR_SET_EMIN(E) BIND(C)
         IMPORT
         IMPLICIT NONE
         INTEGER(KIND=MPFR_EXP_KIND), INTENT(IN), VALUE :: E
         INTEGER(KIND=c_int) :: MPFR_SET_EMIN
       END FUNCTION MPFR_SET_EMIN
    END INTERFACE
    INTERFACE
       FUNCTION MPFR_SET_EMAX(E) BIND(C)
         IMPORT
         IMPLICIT NONE
         INTEGER(KIND=MPFR_EXP_KIND), INTENT(IN), VALUE :: E
         INTEGER(KIND=c_int) :: MPFR_SET_EMAX
       END FUNCTION MPFR_SET_EMAX
    END INTERFACE
    INTEGER(KIND=MPFR_PREC_KIND), INTENT(IN), OPTIONAL :: P
    INTEGER(KIND=MPFR_RND_KIND), INTENT(IN), OPTIONAL :: R
    INTEGER(KIND=MPFR_EXP_KIND), INTENT(IN), OPTIONAL :: EXP_MIN, EXP_MAX
    INTEGER :: MPFR_INITIALIZE
    MPFR_INITIALIZE = 0
    IF (PRESENT(EXP_MAX)) THEN
       IF ((EXP_MAX .GE. MPFR_GET_EMAX_MIN()) .AND. (EXP_MAX .LE. MPFR_GET_EMAX_MAX())) THEN
          MPFR_EXP_MAX = EXP_MAX
       ELSE ! error
          MPFR_INITIALIZE = -4
       END IF
    ELSE
       MPFR_EXP_MAX = MPFR_GET_EMAX_MAX()
    END IF
    IF (MPFR_INITIALIZE .NE. 0) RETURN
    IF (PRESENT(EXP_MIN)) THEN
       IF ((EXP_MIN .GE. MPFR_GET_EMIN_MIN()) .AND. (EXP_MIN .LE. MPFR_GET_EMIN_MAX())) THEN
          MPFR_EXP_MIN = EXP_MIN
       ELSE ! error
          MPFR_INITIALIZE = -3
       END IF
    ELSE
       MPFR_EXP_MIN = MPFR_GET_EMIN_MIN()
    END IF
    IF (MPFR_INITIALIZE .NE. 0) RETURN
    IF (PRESENT(R)) THEN
       IF ((R .GE. MPFR_RNDN) .AND. (R .LE. MPFR_RNDF)) THEN
          MPFR_RND_DEFAULT = R
       ELSE ! error
          MPFR_INITIALIZE = -2
       END IF
    ELSE
       MPFR_RND_DEFAULT = MPFR_GET_DEFAULT_ROUNDING_MODE()
    END IF
    IF (MPFR_INITIALIZE .NE. 0) RETURN
    IF (PRESENT(P)) THEN
       IF ((P .GE. MPFR_PREC_MIN) .AND. (P .LE. MPFR_PREC_MAX)) THEN
          MPFR_PREC_DEFAULT = P
       ELSE ! error
          MPFR_INITIALIZE = -1
       END IF
    ELSE
       MPFR_PREC_DEFAULT = MPFR_GET_DEFAULT_PREC()
    END IF
    IF (MPFR_INITIALIZE .NE. 0) RETURN
    MPFR_INITIALIZE = INT(MPFR_SET_EMAX(MPFR_EXP_MAX))
    IF (MPFR_INITIALIZE .NE. 0) RETURN
    MPFR_INITIALIZE = INT(MPFR_SET_EMIN(MPFR_EXP_MIN))
    IF (MPFR_INITIALIZE .NE. 0) RETURN
    CALL MPFR_SET_DEFAULT_ROUNDING_MODE(MPFR_RND_DEFAULT)
    CALL MPFR_SET_DEFAULT_PREC(MPFR_PREC_DEFAULT)
  END FUNCTION MPFR_INITIALIZE
  SUBROUTINE MPFR_FINALIZE()
